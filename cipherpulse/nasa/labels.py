"""Data-origin labels and the provenance store. Real NASA data, simulations and derived values are never mixed unlabeled."""
import json
import sqlite3
import threading
import time
from pathlib import Path

from .. import config

LABELS = {
    "NASA_OBSERVED": "Measurement or event record published by NASA (for example DONKI space-weather events).",
    "NASA_RESEARCH": "Published NASA research data or metadata (OSDR studies, NTRS reports, Human Research Roadmap).",
    "NASA_DERIVED": "Computed by this application from NASA data. The method is recorded with the record.",
    "EXTERNAL_RESEARCH": "Research outside NASA repositories (for example a GEO accession referenced by an OSDR study).",
    "SIMULATED_DEMO": "Generated by this demo's simulator. Not real astronaut telemetry.",
    "UNAVAILABLE": "Could not be retrieved. The reason is stated. Nothing is invented in its place.",
}
NASA_DIR = config.DATA / "nasa"
for d in ("raw", "processed", "metadata", "cache"):
    (NASA_DIR / d).mkdir(parents=True, exist_ok=True)


class Provenance:
    """SQLite table of everything retrieved or processed, with source, id, units, URL, timestamp and status."""

    def __init__(self, path=None):
        self.db = sqlite3.connect(path or config.DB_PATH, check_same_thread=False)
        self.lock = threading.Lock()
        self.db.execute("""CREATE TABLE IF NOT EXISTS nasa_records(
            id INTEGER PRIMARY KEY AUTOINCREMENT, label TEXT, source TEXT, source_id TEXT, title TEXT,
            details TEXT, units TEXT, source_url TEXT, retrieved_at TEXT, status TEXT, local_path TEXT,
            UNIQUE(source, source_id, local_path))""")
        self.db.commit()

    def record(self, label, source, source_id, title="", details=None, units=None, source_url="", status="retrieved", local_path=""):
        assert label in LABELS, f"unknown label {label}"
        now = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
        with self.lock:
            self.db.execute(
                """INSERT INTO nasa_records(label,source,source_id,title,details,units,source_url,retrieved_at,status,local_path)
                   VALUES(?,?,?,?,?,?,?,?,?,?)
                   ON CONFLICT(source,source_id,local_path) DO UPDATE SET label=excluded.label,title=excluded.title,details=excluded.details,
                   units=excluded.units,source_url=excluded.source_url,retrieved_at=excluded.retrieved_at,status=excluded.status""",
                (label, source, str(source_id), title, json.dumps(details or {}), json.dumps(units or {}), source_url, now, status, local_path))
            self.db.commit()

    def list(self, label=None, source=None, limit=200):
        q, a = "SELECT label,source,source_id,title,details,units,source_url,retrieved_at,status,local_path FROM nasa_records", []
        w = []
        if label:
            w.append("label=?"); a.append(label)
        if source:
            w.append("source=?"); a.append(source)
        if w:
            q += " WHERE " + " AND ".join(w)
        q += " ORDER BY id DESC LIMIT ?"
        a.append(limit)
        keys = ["label", "source", "source_id", "title", "details", "units", "source_url", "retrieved_at", "status", "local_path"]
        out = []
        for r in self.db.execute(q, a).fetchall():
            d = dict(zip(keys, r))
            d["details"], d["units"] = json.loads(d["details"] or "{}"), json.loads(d["units"] or "{}")
            out.append(d)
        return out

    def counts(self):
        return {l: n for l, n in self.db.execute("SELECT label, COUNT(*) FROM nasa_records GROUP BY label")}


def write_sidecar(name: str, payload: dict) -> str:
    p = NASA_DIR / "metadata" / (Path(name).name + ".json")
    p.write_text(json.dumps(payload, indent=2, default=str))
    return str(p)
